import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const context={exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/features/samples/characterization-data.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,context);
const{normalizeCharacterizationData,collectAssetPaths,replaceAssetPaths,collectWorkspacePaths}=context.exports;
const raw={Laser:'632.799987 nm',Power:'500 µW',__order__:['Laser','Power'],local_h5_paths:['Book/Sample/RAMAN/2026/Old.h5'],attached_images:['Book/image.png']};
const manual=normalizeCharacterizationData(raw,'Raman');
const wip=normalizeCharacterizationData({...raw,wip_import:{source_hash:'a'.repeat(64),object_id:'21',original_metadata:{laser_wavelength_nm:632.799987},library:{relative_path:'Projects/Project.wip'},attached_image_metadata:[{path:'Book/original.png',annotated_path:'Book/image.png'}]}},'Raman');
assert.equal(JSON.stringify(manual.asset_manifest.reviewed_parameters),JSON.stringify(wip.asset_manifest.reviewed_parameters));
assert.equal(wip.asset_manifest.source.locator.relative_path,'Projects/Project.wip');
assert.equal(wip.wip_import.original_metadata.laser_wavelength_nm,632.799987);
assert.ok(collectAssetPaths(wip).includes('Book/original.png'));
const moved=replaceAssetPaths(wip,{'Book/Sample/RAMAN/2026/Old.h5':'Book/Sample/RAMAN/2026/A24_RAMAN_632.8nm_Spot1.h5'});
assert.ok(moved.local_h5_paths[0].includes('Spot1'));
assert.equal(raw.local_h5_paths[0],'Book/Sample/RAMAN/2026/Old.h5','path updates never mutate input metadata');
assert.equal(collectWorkspacePaths({files:[{h5_relative_path:'Book/Parent.h5'}],settings:{source:'Book/Child.h5'}}).length,2);
console.log('PASS unified characterization schema: manual/WIP parameters, portable locators, original metadata, path updates, workspace references');
