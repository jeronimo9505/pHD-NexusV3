import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const context = { exports: {}, structuredClone };
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/features/map-analyzer/spectroview/model-operations.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText, context);
const { removePeak } = context.exports;
const model = { peak_models: Object.fromEntries(Array.from({ length: 11 }, (_, i) => [String(i), { Lorentzian: { x0: { value: 100 + i, min: 0, max: 200, vary: false }, fwhm: { value: 10 } } }])) };
model.peak_models[10].Lorentzian.fwhm.expr = 'P10_fwhm + P2_fwhm';
const snapshot = JSON.stringify(model);
const next = removePeak(model, '0');
assert.equal(next.peak_models[9].Lorentzian.fwhm.expr, 'P9_fwhm + P1_fwhm');
assert.deepEqual(next.peak_models[0].Lorentzian.x0, model.peak_models[1].Lorentzian.x0);
assert.equal(JSON.stringify(model), snapshot);
assert.throws(() => removePeak(model, '1'), /depends on P2_fwhm/);
assert.equal(JSON.stringify(model), snapshot);
assert.throws(() => removePeak({ peak_models: { 0: model.peak_models[0] } }, '0'), /at least one/);
assert.throws(() => removePeak(model, '20'), /does not exist/);
const middle = removePeak(model, '4');
assert.equal(middle.peak_models[9].Lorentzian.fwhm.expr, 'P9_fwhm + P2_fwhm');
console.log('PASS safe peak deletion: identity, constraints, expressions, multi-digit references, and atomic rejection');
