import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const context = {exports:{}};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/features/map-analyzer/workspace-display.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText, context);
const {resolveWorkspaceSample,measurementChips,laserAppearance,physicalMapSize,reviewedMeasurementParameters} = context.exports;
const samples = [{id:'p',sample_code:'A23',name:'Au'}, {id:'c',sample_code:'A23-c3',name:'Graphene',parent_id:'p'}, {id:'other',sample_code:'A2',name:'Au'}];
const file = {name:'A23-c3_RAMAN_999nm_0.5mW_0.5s_Spot2.h5',sample_name:'Au',h5_relative_path:'Book/A23-c3 - Graphene/RAMAN/2026/file.h5'};
assert.equal(resolveWorkspaceSample(file,samples).id,'c');
assert.equal(resolveWorkspaceSample({...file,name:'WIP_uuid.h5'},samples).id,'c');
assert.equal(resolveWorkspaceSample({...file,sample_id:'other'},samples).id,'other');
assert.equal(resolveWorkspaceSample({...file,name:'A230_RAMAN.h5',h5_relative_path:'unknown.h5'},samples),undefined);
const parameters={Laser:'632.7999877929688 nm',Power:'500 µW',Spots:'50x50 ixj',Size:'200x200 µm'};
const display=measurementChips({...file,parameters});
assert.equal(display.source,'metadata');
assert.equal(display.chips.find(chip=>chip.type==='laser').label,'632.8nm');
assert.equal(display.spot,'Spot2');
assert.ok(!display.chips.some(chip=>chip.label==='999nm'));
assert.equal(measurementChips(file).chips.find(chip=>chip.type==='time').label,'0.5s');
assert.equal(measurementChips(file).chips.find(chip=>chip.type==='power').label,'0.5mW');
assert.equal(laserAppearance('633nm').band,'Red');
assert.equal(laserAppearance('532 nm').band,'Green');
assert.equal(laserAppearance('785nm').band,'NIR');
assert.equal(physicalMapSize(parameters).width,200);
assert.equal(physicalMapSize({Size:'0.2x0.1 mm'}).height,100);
assert.equal(reviewedMeasurementParameters({Laser:'999nm',asset_manifest:{reviewed_parameters:parameters}}).Laser,parameters.Laser);
console.log('PASS workspace: exact child identity, ambiguous names, metadata over filename, decimals, laser bands and pixels vs physical extent');
